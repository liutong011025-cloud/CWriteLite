const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('lib/database-config.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const mod = { exports: {} }; new Function('exports', 'module', compiled)(mod.exports, mod);
const { runtimeDatabaseUrl, WRITING_TRANSACTION_OPTIONS } = mod.exports;
const direct = 'postgresql://user:encoded%40password@db.prisma.io:5432/postgres?sslmode=require&schema=public&connection_limit=3';
const result = new URL(runtimeDatabaseUrl(direct));
const original = new URL(direct);
assert.equal(result.hostname, 'pooled.db.prisma.io');
for (const part of ['protocol', 'username', 'password', 'port', 'pathname']) assert.equal(result[part], original[part]);
for (const [key, value] of original.searchParams) assert.equal(result.searchParams.get(key), value);
assert.equal(original.hostname, 'db.prisma.io');
const recording = new URL(runtimeDatabaseUrl(direct, 'recording'));
assert.equal(recording.hostname, result.hostname); assert.equal(recording.searchParams.get('connection_limit'), '4'); assert.equal(recording.searchParams.get('pool_timeout'), '5');
const local = new URL(runtimeDatabaseUrl('postgresql://test@127.0.0.1:54348/postgres?connection_limit=1&pool_timeout=4'));
assert.equal(local.hostname, '127.0.0.1'); assert.equal(local.searchParams.get('connection_limit'), '1'); assert.equal(local.searchParams.get('pool_timeout'), '4');
assert.equal(new URL(runtimeDatabaseUrl('postgresql://u:p@db.prisma.io.example.org/db')).hostname, 'db.prisma.io.example.org');
assert.equal(new URL(runtimeDatabaseUrl('postgresql://u:p@pooled.db.prisma.io/db')).hostname, 'pooled.db.prisma.io');
assert.equal(runtimeDatabaseUrl('prisma://accelerate.prisma-data.net/?api_key=placeholder'), 'prisma://accelerate.prisma-data.net/?api_key=placeholder');
assert.equal(runtimeDatabaseUrl(undefined), undefined);
assert.equal(new URL(runtimeDatabaseUrl('postgresql://u:p@db.prisma.io/db')).searchParams.get('connection_limit'), '5');
assert.deepEqual(WRITING_TRANSACTION_OPTIONS, { maxWait: 5000, timeout: 15000 });
const errorCompiled = ts.transpileModule(fs.readFileSync('lib/database-error.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const errorMod = { exports: {} }; new Function('exports', 'module', 'require', errorCompiled)(errorMod.exports, errorMod, require);
const { Prisma } = require('@prisma/client');
for (const code of ['P1001', 'P2024', 'P2028']) assert.equal(errorMod.exports.databaseUnavailable(new Prisma.PrismaClientKnownRequestError('test', { code, clientVersion: '6.19.2' })), true);
assert.equal(errorMod.exports.databaseUnavailable(new Prisma.PrismaClientKnownRequestError('test', { code: 'P2002', clientVersion: '6.19.2' })), false);
assert.equal(errorMod.exports.databaseUnavailable(new Error('fal error')), false);
console.log('Database configuration checks passed: pooled application traffic, unchanged migration source and bounded separate client pools.');
